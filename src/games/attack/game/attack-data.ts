export function outcome(
  survival: number,
  trust: number,
  answersOrLast: readonly number[] | number = [],
): Outcome {
  const answers = typeof answersOrLast === "number" ? [] : answersOrLast;
  const last =
    typeof answersOrLast === "number"
      ? answersOrLast
      : (answers[missions.length - 1] ?? -1);

  if (survival >= 80 && trust >= 80 && isAotHiddenRoute(answers)) {
    return "hidden";
  }
  if (survival >= 80 && trust >= 80) {
    return "hero";
  }
  if (trust >= 70 && last === SACRIFICE_LAST_CHOICE_INDEX) {
    return "sacrifice";
  }
  if (survival >= 65) {
    return "survivor";
  }
  return "fallen";
}

