export function isPierreSecretRoute(answers: number[]): boolean {
  return (
    answers[PIERRE_SECRET_KEYS.invitationStage] ===
      PIERRE_SECRET_KEYS.invitationChoice &&
    answers[PIERRE_SECRET_KEYS.blackHeartStage] ===
      PIERRE_SECRET_KEYS.blackHeartChoice &&
    answers[PIERRE_SECRET_KEYS.finalHeartStage] ===
      PIERRE_SECRET_KEYS.finalHeartChoice
  );
}

export function getEnding(
  heart: number,
  virtue: number,
  answers: number[] = [],
): SugarEnding {
  if (heart >= 80 && isPierreSecretRoute(answers)) {
    return endings[0]!;
  }
  if (heart >= 80 && virtue >= 80) {
    return endings[1]!;
  }
  if (heart >= 80 && virtue >= 40) {
    return endings[2]!;
  }
  if (virtue >= 80 && heart >= 40) {
    return endings[3]!;
  }
  return endings[4]!;
}

