export const clamp = (v: number) => Math.max(0, Math.min(100, v));

export function characterAssessments(answers: number[]) {
  return judges.map((name, j) => {
    const delta = answers.reduce(
      (sum, answer, i) => sum + (judgeEffects[i]?.[answer]?.[j] ?? 0),
      0,
    );
    const score = clamp(50 + delta);
    const grade =
      score >= 75 ? "S" : score >= 60 ? "A" : score >= 45 ? "B" : score >= 30 ? "C" : "D";
    const profile = judgeProfiles[name];
    return {
      name,
      role: profile.role,
      score,
      grade,
      focus: profile.focus,
      comment: score >= 70 ? profile.high : score >= 45 ? profile.mid : profile.low,
    };
  });
}
